#!/usr/bin/env python3
"""Generate recipes/_musl_dep_symbols.py: the names of libuv and OpenSSL code.

    musl_dep_symbols.py NAMES_OUT.py --project PROJECT_NAMES.txt ARCHIVE...

Why this exists. The static musl images carry libuv and OpenSSL (a static ELF
cannot load a shared library), and Recipe.exclude_functions removes functions
by name. The list of names is not something to write by hand - OpenSSL 3.5.8
defines 20,000 functions - so it is read from the archives the recipes link:
every function symbol that nm finds defined in libuv.a, libcrypto.a and
libssl.a of both architectures. Archives, not the images: the list says what
libuv and OpenSSL are, and does not depend on which part of them a miner
happens to pull in.

A name becomes a prefix rule (`EVP` for every `EVP_*`) when the token before
its first underscore is shared by at least three of the archive's functions
and by no function of the miner's own code, and an exact name otherwise.
PROJECT_NAMES.txt is those miner functions, one per line: the functions of the
images that the linker map attributes to the project's own objects. A name that
the archives define and the project also has (`blake2b`, `do_...` statics) is
reported and left out: excluding it would delete miner code, which is the one
thing this list must never do.

The output is a module with PREFIXES, EXACT and EXCLUDE (two regular
expressions), and the pinned versions it was generated from. Regenerate it
when the pins in _stack_deps.py move.
"""

import argparse
import collections
import re
import subprocess
import sys


def archive_names(path):
    out = subprocess.run(["nm", "--defined-only", path], capture_output=True,
                         text=True, errors="replace", check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TtWwiI":
            names.add(parts[2])
    return names


def token(name):
    match = re.match(r"_*[^_]+", name)
    return match.group(0)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("output")
    parser.add_argument("--project", required=True)
    parser.add_argument("archives", nargs="+")
    args = parser.parse_args()

    names = set()
    for archive in args.archives:
        names |= archive_names(archive)
    with open(args.project) as handle:
        project = {line.rstrip("\n") for line in handle if line.strip()}

    collisions = sorted(names & project)
    names -= set(collisions)
    members = collections.defaultdict(set)
    for name in names:
        if "_" in name[len(token(name)):]:
            members[token(name)].add(name)
    project_tokens = {token(p) for p in project if "_" in p[len(token(p)):]}
    project_prefix = set()
    for p in project:
        # every p[:i] that ends where an underscore follows
        for match in re.finditer(r"_", p):
            project_prefix.add(p[:match.start()])
    prefixes = sorted(t for t, group in members.items()
                      if len(group) >= 3 and t not in project_prefix
                      and t not in project)
    covered = {n for t in prefixes for n in members[t]}
    exact = sorted(names - covered)
    with open(args.output, "w") as out:
        out.write('"""Names of libuv and OpenSSL code, for the static musl recipes.\n\n'
                  "GENERATED by exercisers/musl_dep_symbols.py from the function symbols\n"
                  "of libuv 1.52.1 and OpenSSL 3.5.8 as built by the musl recipes (libuv.a,\n"
                  "libcrypto.a, libssl.a; x64 and x86). Do not edit; regenerate when the\n"
                  "versions pinned in _stack_deps.py change.\n\n"
                  "%d prefix rules and %d exact names; %d names the archives and the\n"
                  "miner share were left out (%s).\n"
                  '"""\n\n' % (len(prefixes), len(exact), len(collisions),
                               ", ".join(collisions[:6]) + (", ..." if len(collisions) > 6 else "")))
        out.write("import re\n\n")
        out.write("PREFIXES = (\n")
        for item in prefixes:
            out.write("    %r,\n" % item)
        out.write(")\n\nEXACT = (\n")
        for item in exact:
            out.write("    %r,\n" % item)
        out.write(""")

EXCLUDE = [
    "^(?:%s)_" % "|".join(re.escape(p) for p in PREFIXES),
    "^(?:%s)$" % "|".join(re.escape(n) for n in EXACT),
]
""")
    print("names %d (collisions left out: %d), prefix rules %d covering %d, exact %d"
          % (len(names), len(collisions), len(prefixes), len(covered), len(exact)))
    if collisions:
        print("collisions:", " ".join(collisions))


if __name__ == "__main__":
    sys.exit(main())
