#!/usr/bin/env python3
"""Generate recipes/_openssh_musl_symbols.py: names of zlib, OpenSSL and musl code.

    openssh_musl_symbols.py OUT.py --project DIR_OR_FILE... \
        --lib zlib=libz.a --lib openssl=libcrypto.a --lib openssl=libssl.a \
        --lib libc=libc.a ...

Why this exists. The static musl OpenSSH images carry zlib, OpenSSL and the
parts of musl's libc that the glue baseline does not name, and
Recipe.exclude_functions removes functions by name. The names are read from
the archives that were linked, not written by hand: every function symbol
``nm`` finds defined in each --lib archive (T, t, W, w, i, I), the union over
every architecture and release the archives were taken from.

A name is excluded only if it is the library's and nothing of OpenSSH's. --project
takes the build trees (directories searched for *.o and *.a, or single files):
every symbol of any kind that OpenSSH's own objects and its two internal
archives (libssh.a, libopenbsd-compat.a) define, over all the releases and
architectures given. A library name that the project also defines (for
example a compat replacement for a libc function, or a file-local static that
happens to share a name) is a COLLISION and is left out of the exact-name
table: excluding it would delete OpenSSH code, which is the one thing this
list must never do. The collisions are recorded in the output.

The output module has one exact-name tuple per library label, the collisions,
and EXCLUDE: one regular expression per label (anchored, a trie of the names so
a match costs the length of the name and not the size of the table).
"""

import argparse
import collections
import os
import subprocess
import sys

FUNCTION_TYPES = "TtWwiI"


def nm_symbols(path, types=None):
    out = subprocess.run(["nm", "--defined-only", path], capture_output=True,
                         text=True, errors="replace", check=False).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        # ".L..." are assembler-local labels, never function names in an image
        if (len(parts) == 3 and (types is None or parts[1] in types)
                and not parts[2].startswith(".L")):
            names.add(parts[2])
    return names


def project_names(roots):
    names = set()
    for root in roots:
        if os.path.isfile(root):
            names |= nm_symbols(root)
            continue
        for base, _dirs, files in os.walk(root):
            for name in files:
                if name.endswith((".o", ".a")):
                    names |= nm_symbols(os.path.join(base, name))
    return names


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("output")
    parser.add_argument("--project", nargs="+", required=True)
    parser.add_argument("--lib", action="append", required=True,
                        help="LABEL=ARCHIVE; repeat, labels may repeat")
    parser.add_argument("--note", default="")
    args = parser.parse_args()

    project = project_names(args.project)
    libs = collections.OrderedDict()
    for spec in args.lib:
        label, path = spec.split("=", 1)
        libs.setdefault(label, set()).update(nm_symbols(path, FUNCTION_TYPES))
    taken = set()
    exact = collections.OrderedDict()
    collisions = collections.OrderedDict()
    for label, names in libs.items():
        mine = {n for n in names if n not in project and n not in taken}
        collisions[label] = sorted(n for n in names if n in project)
        exact[label] = sorted(mine)
        taken |= mine

    with open(args.output, "w") as out:
        out.write('"""Names of zlib, OpenSSL and musl libc code, for the static musl OpenSSH recipes.\n\n')
        out.write("GENERATED by exercisers/openssh_musl_symbols.py; do not edit. %s\n\n" % args.note)
        out.write("EXACT[label] is every function symbol defined by the pinned static\n"
                  "archive(s) of that label (union over the architectures and releases built)\n"
                  "that no OpenSSH object defines. COLLISIONS[label] is the library names that\n"
                  "OpenSSH's own objects also define; they are not excluded.\n\n")
        for label in exact:
            out.write("%-8s %5d exact names, %3d collisions left out\n"
                      % (label, len(exact[label]), len(collisions[label])))
        out.write('"""\n\n')
        out.write('''import re


def _trie(names):
    """A regular expression matching exactly ``names`` (a character trie)."""
    root = {}
    for name in names:
        node = root
        for char in name:
            node = node.setdefault(char, {})
        node[""] = {}

    def render(node):
        if list(node) == [""]:
            return ""
        parts = []
        end = "" in node
        for char in sorted(k for k in node if k):
            parts.append(re.escape(char) + render(node[char]))
        body = parts[0] if len(parts) == 1 else "(?:" + "|".join(parts) + ")"
        return "(?:" + body + ")?" if end else body

    return "^" + render(root) + "$"


''')
        out.write("EXACT = {\n")
        for label, names in exact.items():
            out.write("    %r: (\n" % label)
            for n in names:
                out.write("        %r,\n" % n)
            out.write("    ),\n")
        out.write("}\n\nCOLLISIONS = {\n")
        for label, names in collisions.items():
            out.write("    %r: (\n" % label)
            for n in names:
                out.write("        %r,\n" % n)
            out.write("    ),\n")
        out.write("}\n\nEXCLUDE = [_trie(EXACT[label]) for label in EXACT]\n")
    for label in exact:
        print("%s: %d exact, %d collisions" % (label, len(exact[label]), len(collisions[label])))
    for label in collisions:
        print(label, "collisions:", " ".join(collisions[label][:40]))


if __name__ == "__main__":
    sys.exit(main())
