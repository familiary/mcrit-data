"""Vendored code in the SoftEther VPN 5.x Linux libraries, as exact names.

SoftEther 5.x links four third-party code bases into its two Linux libraries
that are not SoftEther's: liboqs and the OQS provider (the Open Quantum Safe
submodules src/Mayaqua/3rdparty/liboqs and oqs-provider, built as static
archives and linked into libmayaqua.so because the host's OpenSSL is 3.x, so
upstream's OQS_ENABLE default is on), google/cpu_features (a static archive,
also into libmayaqua.so) and BLAKE2's blake2s (3rdparty/BLAKE2/sse/blake2s.c,
compiled straight into libcedar.so). OpenSSL, zlib, libsodium, readline and
ncurses are linked dynamically and are not in the images at all, which is
the difference from the Stable 4.x Windows images that
_softether_vendored.py handles.

The evidence is stronger than the P/W/N tiers that module needs, because the
build that produced the images also produced the libraries' own archives: a
name is listed only if it is a function defined (nm --defined-only, types T,
t, W or i) in liboqs.a, liboqs-internal.a, liboqsprovider.a,
libcpu_features.a or the blake2s object, and NOT defined in any of
SoftEther's own objects (Cedar, Mayaqua and libhamcore); no name was in both.
That is the same membership test the XMRig/xmrig-proxy musl recipes use for
libuv and OpenSSL ("excluded by name from the pinned archives"). It is exact
names, anchored, so nothing SoftEther defines can match.

What it removes, measured on the x64 images (kept + removed as runtime +
excluded = total):

  libmayaqua.so  liboqs 844 names / 860 functions, oqs-provider 261 / 261,
                 cpu_features 105 / 105
  libcedar.so    BLAKE2 (blake2s) 7 / 7

and on x86 873 functions from libmayaqua.so and the same 7 from libcedar.so.
The table was taken from the x64 archives first; the x86 archives define 30
more liboqs names (the 32-bit KeccakP1600 and KeccakP1600times4 code and
OQS_randombytes_system.cold) that occur in the x86 image, and they are
listed with the rest, so both architectures are excluded from one table.

Left in: 543 unnamed functions in libmayaqua.so and 1854 in libcedar.so,
which no name pattern can reach. 1852 of libcedar.so's and 475 of
libmayaqua.so's are three instructions or fewer (PLT stubs into the dynamic
libraries); 53 of libmayaqua.so's are ten or more, and how many of those are
liboqs code is not known. data/BLAKE2 exists, so
blake2s is excluded rather than filed under SoftEther; there is no liboqs,
oqs-provider or cpu_features family in the corpus to file the rest under.
"""

