"""Code the SoftEther Windows images carry that other corpus families carry, as exact names.

The Windows programs link the OpenSSL, zlib and intel-aes static libraries that
upstream ships under src/BuildFiles/Library (libeay32.lib, ssleay32.lib,
zlib.lib, libintelaes.lib), plus a few small cryptographic helpers, and that
code lands in the images under SoftEtherVPN's name. Recipe.exclude_functions
(PR #94) removes it by name. The recipe sets the patterns built here, one per
category, from the tables below.

The images were re-derived from their committed .7z archives, not rebuilt:
functions removed from the report and the export, provenance gains
exclude_functions, excluded_function_count and num_functions_before_exclusion,
so kept + removed as runtime + excluded is each image's total as before.

An identifier is exact: x64 names as they are, x86 names with the C decoration
(`_ASN1_INTEGER_new`), so a name is in a table only if EVERY function of that
exact name in the recipe's eight images is shown to be the library's. The
evidence comes in three tiers, counted separately:

  P  PicHash. The function's PicHash equals the PicHash of a same-named
     function (a leading C underscore ignored for x86 images) in the library's
     own family: data/OpenSSL (1.0.2u, 1.1.1w, 3.0.15 and 3.5.8, MSVC, MinGW
     and GCC; the MSVC 1.0.2u, 3.0.15 and 3.5.8 images are on
     claude/corpus-openssl-add, not yet on main), data/libzlib (1.0.4 to
     1.3.1) or data/libsodium (1.0.18, 1.0.20). A function of fewer than ten
     instructions counts when its PicHash is that of a same-named library
     function.
  W  Weaker. No PicHash match, but a same-named function of the same
     architecture in that family whose mnemonic sequence (frame-pointer
     set-up, leave, ret and nop/int3 padding dropped; difflib ratio) is at
     least 80% similar, and only for an identifier of which another function
     in the recipe, on the other architecture or in another program, is P.
     It is the same code built with other flags: the vendored OpenSSL is a
     different build from every family (x86 above all: the x86 library images
     are /MD builds with other options). The lowest ratio used is 0.80; of the
     5,332 W functions 3,116 are under ten instructions, below MCRIT's floor.
  N  Name. No corpus family carries the code, so the identifier is the
     library's by what it is called, in full: intel-aes's exports
     (`iEnc128`, `iDecExpandKey256_CBC`... and `intel_AES_*`, plus its
     `check_for_aes_instructions`; libintelaes.lib is one of the four
     vendored libraries the helper links, and every program has the same
     function under each name with one PicHash per architecture), and the
     OpenSSL legacy provider's `ossl_*` functions, a prefix OpenSSL reserves
     for its internals, which none of the loaded OpenSSL, LibreSSL,
     BoringSSL, wolfSSL, mbedTLS, libgcrypt, libtomcrypt, Crypto++, libzlib
     or libsodium images define (they are built without the legacy provider).
     This is the weakest tier and the only one there is for these names.

What is removed (8 images, 23,092 functions, 5,739 exact names):

  tier  OpenSSL  zlib  libsodium  intel-aes  OpenSSL legacy   all
  P      17,152    64          8          -               -  17,224
  W       5,300    24          8          -               -   5,332
  N           -     -          -        296             240     536

By image: x64 3,005 each (2,765 P, 173 W, 67 N), x86 2,768 each (1,541 P,
1,160 W, 67 N); the four programs of an architecture are identical here.
Exact names: OpenSSL 5,608, zlib 11, libsodium 2, intel-aes 58, legacy 60.

Measured and deliberately left in (x64 vpnserver; x86 is within 2%):

  * 6,300 anonymous functions (6,219 on x86; empty name). Nearly all are
    OpenSSL statics, but a name pattern cannot reach them and none is
    removed. A link map (`build-<arch>/<program>.map`, written by the helper
    and not part of the artefacts) would attribute them by source object
    (libeay32.lib and the others); that needs an exclusion by address,
    which Recipe.exclude_functions is not, and a rebuild whose output is the
    committed binary, so it was not done.
  * 3,951 named functions (4,133 on x86) whose name is an OpenSSL name but
    that have no P function in the recipe: the vendored OpenSSL is a different
    build from every family here, and an identifier without a P function is
    not W-eligible. They stay. The same applies to 87 zlib-named functions of
    which only 11 identifiers (adler32, crc32_combine, deflateInit_,
    fixedtables, get_crc_table, inflateInit_, tr_static_init, uncompress,
    zError, zlibCompileFlags, zlibVersion) are P; `deflate`, `inflate`,
    `crc32` and the rest differ in PicHash from every libzlib image, and
    their opcode similarity (0.4 to 1.0) is not a basis without a P function.
  * 317 exact names that are not wholly shown. 309 are the other spelling of
    an identifier that is P in one architecture and below 0.80 in the other
    (x86 `_OCSP_resp_get0` 0.67, `_EVP_CIPHER_CTX_new` 0.75,
    `_BIO_sock_init` 0.79), or, for x86 `_poly1305_blocks` (0.83 against
    OpenSSL), the spelling of an identifier whose x64 function has a second
    same-named function that is not OpenSSL's (0.63): an identifier is
    excluded whole, so it stays. Those have no P function of their own, so W
    does not apply. 8 have a P function and another that is neither P nor 80%
    similar: zlib's `compress`, `putShortMSB`, `adler32_combine`,
    `adler32_combine64`, `crc32_combine64`, `_tr_init`, `_tr_flush_bits`, and
    x64 `poly1305_blocks`, whose second function per image is another
    implementation. Each stays whole.
  * Import thunks and inline helpers that share a PicHash with the same-named
    function of the OpenSSL and zlib DLLs but are not the library's code:
    single `jmp [__imp_...]` stubs such as `Sleep`, `WSAStartup`, `send`,
    `strcpy_s`, `wcstombs`, and the Wspiapi* and MarkAllocaS helpers. 788
    functions in 190 names were refused on that ground and are not in any
    table.
  * Toolchain code: the delay-load helpers (`__delayLoadHelper2`, `Dload*`,
    `PFromRva<...>`, `__tailMerge_*`, 145 or 147 `__imp_load_*` thunks;
    about 535 functions), which the PR already lists as glue the baseline
    does not know; and SoftEther's own code, including the code it vendors
    that no family carries (parson's `json_*` and `parse_*`, and the
    chacha20/poly1305 reference code named `chacha20_encrypt_bytes`,
    `crypto_onetimeauth_poly1305_*`: generic names, and libsodium's family
    holds a different implementation of the same primitives).
"""

