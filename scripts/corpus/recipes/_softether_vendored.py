def _trie(names):
    root = {}
    for name in names:
        node = root
        for char in name:
            node = node.setdefault(char, {})
        node[""] = True
    return root


def _render(node):
    alternatives = [re.escape(char) + _render(child)
                    for char, child in sorted(node.items()) if char]
    if not alternatives:
        return ""
    body = alternatives[0] if len(alternatives) == 1 \
        else "(?:%s)" % "|".join(alternatives)
    return "(?:%s)?" % body if "" in node else body


def exact_names(names):
    """One anchored regular expression over exact function names.

    The names are escaped and merged into a prefix tree, so the expression is
    a fraction of the size of the plain alternation and still matches nothing
    but those strings: not a prefix, not a method of the same class, not the
    other architecture's spelling of a name (`_X` and `X` are separate
    entries).
    """
    return "^%s$" % _render(_trie(sorted(set(names))))


def patterns():
    """The recipe's exclude_functions patterns, one per category."""
    return [exact_names(NAMES[category]) for category in CATEGORIES]
